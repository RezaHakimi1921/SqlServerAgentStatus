def normalize_locale(locale: Optional[str]) -> str:
    raw = (locale or DEFAULT_LOCALE).strip().lower()
    if raw.startswith("fa") or raw in ("fa-ir", "persian", "farsi"):
        return "fa"
    return "en"


def is_rtl(locale: Optional[str]) -> bool:
    return normalize_locale(locale) == "fa"


def t(key: str, locale: Optional[str] = None, **kwargs: Any) -> str:
    """Translate key; fall back to English then to the key itself."""
    loc = normalize_locale(locale)
    text = STRINGS.get(loc, {}).get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def module_title(module_id: str, locale: Optional[str] = None) -> str:
    return t(f"module.{module_id}.title", locale)


def module_subtitle(module_id: str, locale: Optional[str] = None) -> str:
    return t(f"module.{module_id}.subtitle", locale)
